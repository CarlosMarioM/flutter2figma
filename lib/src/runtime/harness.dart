/// The Flutter test that runtime capture writes into the app (under
/// `.dart_tool/flutter2figma/`) and runs with `flutter test`.
///
/// It starts the app through its own `main()`, so dependency injection,
/// providers and themes are set up as in the real app. Then it pushes each
/// screen onto the app's root navigator and records what Flutter rendered:
/// a tree of boxes, text, icons and images with their exact positions.
/// Anything painted by a `CustomPainter` (switches, checkboxes, charts, ...)
/// is rasterized by calling the painter, and unknown leaf render objects are
/// cropped from a screenshot, so every widget comes out as it looks.
///
/// Placeholders replaced by [harnessSource]:
/// - `/*IMPORTS*/`: the app's `main.dart` as `app`, screen libraries as `s0`…
/// - `/*SCREENS*/`: `'Name': () => s0.Name(),` entries.
/// - `/*BUILD*/`: how a screen is built, from `name` and `fallback`.
library;

/// The test file for the given imports and screen builders.
///
/// [setupImports] and [setup] run before the app starts (plugin fakes, the
/// app's own `setUp()`); [wrap] is an expression of `name` and `screen`
/// that wraps each pushed screen, e.g. with providers it expects.
String harnessSource({
  required String mainImport,
  required Map<String, String> screenImports,
  required Map<String, String> screens,
  List<String> setupImports = const [],
  List<String> setup = const [],
  String wrap = 'screen',
  String build = 'fallback()',
  bool nested = false,
}) {
  final imports = [
    "import '$mainImport' as app;",
    for (final MapEntry(:key, :value) in screenImports.entries)
      "import '$key' as $value;",
    ...setupImports,
    if (nested) "import 'package:nested/nested.dart' as nested;",
  ].join('\n');
  final builders = [
    for (final MapEntry(:key, :value) in screens.entries)
      "  '$key': () => $value,",
  ].join('\n');
  return _template
      .replaceFirst('/*IMPORTS*/', imports)
      .replaceFirst('/*SCREENS*/', builders)
      .replaceFirst('/*SETUP*/', setup.join('\n'))
      .replaceFirst('/*WRAP*/', wrap)
      .replaceFirst('/*BUILD*/', build)
      .replaceFirst('/*PROVIDERS*/', nested ? _nestedProviders : _noProviders);
}

const _noProviders = r'''
List<f.Widget> _routeProviders() => const [];

f.Widget _provide(List<f.Widget> providers, f.Widget child) => child;
''';

/// Providers (`BlocProvider`, `Provider`, ...) found on the app's initial
/// route, below the Navigator: screens pushed later get them too, since
/// apps often provide a screen's blocs in the route that shows it.
const _nestedProviders = r'''
List<f.Widget> _routeProviders() {
  final navigators = t.find.byType(f.Navigator).evaluate();
  if (navigators.isEmpty) return const [];
  final found = <f.Widget>[];
  void visit(f.Element e) {
    final widget = e.widget;
    if (widget is nested.SingleChildWidget && widget is! nested.Nested) found.add(widget);
    e.visitChildElements(visit);
  }
  navigators.first.visitChildElements(visit);
  return found;
}

f.Widget _provide(List<f.Widget> providers, f.Widget child) => providers.isEmpty
    ? child
    : nested.Nested(children: providers.cast<nested.SingleChildWidget>(), child: child);
''';

