String? _hex(ui.Color? c) =>
    c == null ? null : '#${c.toARGB32().toRadixString(16).padLeft(8, '0')}';

List<double> _rect(ui.Rect r) => [r.left, r.top, r.width, r.height];

/// Paints one render object without its children, recording the children
/// it would have painted, in paint order. Layer contexts it opens (clips,
/// opacity, transforms) are recording contexts too, so no child ever paints.
class _AloneContext extends r.PaintingContext {
  _AloneContext(super.containerLayer, super.estimatedBounds, this.painted, [this.root]);

  final List<r.RenderObject> painted;

  /// The top-level layer of the replay, and how many of its children were
  /// painted before the first child: what comes after is painted on top of
  /// the children (outlines, borders).
  final r.ContainerLayer? root;
  int? layersBeforeChildren;

  @override
  void paintChild(r.RenderObject child, ui.Offset offset) {
    if (painted.isEmpty) {
      stopRecordingIfNeeded();
      var count = 0;
      for (var l = root?.firstChild; l != null; l = l.nextSibling) {
        count++;
      }
      layersBeforeChildren = count;
    }
    painted.add(child);
  }

  @override
  r.PaintingContext createChildContext(r.ContainerLayer childLayer, ui.Rect bounds) =>
      _AloneContext(childLayer, bounds, painted, root);

  void finish() => stopRecordingIfNeeded();
}

class _Recorder {
  _Recorder(this.screenshot);

  final ui.Image screenshot;
  final images = <String, Uint8List>{};
  final _pending = <String, Future<ui.Image?>>{};

  /// Ids whose images may be fully transparent (painted by code we don't
  /// know): those are dropped.
  final _maybeEmpty = <String>{};
  final _imageIds = <ui.Image, String>{};

  String _id() => 'img${_pending.length}';

  String _encode(ui.Image image) => _imageIds.putIfAbsent(image, () {
    final id = _id();
    const limit = 4096; // Figma's largest image side.
    final scale = limit / (image.width > image.height ? image.width : image.height);
    if (scale >= 1) {
      _pending[id] = Future.value(image);
    } else {
      final w = (image.width * scale).floor(), h = (image.height * scale).floor();
      final recorder = ui.PictureRecorder();
      ui.Canvas(recorder).drawImageRect(
        image,
        ui.Rect.fromLTWH(0, 0, image.width.toDouble(), image.height.toDouble()),
        ui.Rect.fromLTWH(0, 0, w.toDouble(), h.toDouble()),
        ui.Paint()..filterQuality = ui.FilterQuality.medium,
      );
      _pending[id] = recorder.endRecording().toImage(w, h);
    }
    return id;
  });

  /// Runs [painter] alone into an image of [size].
  String? _paint(f.CustomPainter painter, ui.Size size) {
    if (size.isEmpty) return null;
    final recorder = ui.PictureRecorder();
    final canvas = ui.Canvas(recorder)..scale(_scale);
    try {
      painter.paint(canvas, size);
    } catch (_) {
      return null;
    }
    final picture = recorder.endRecording();
    final id = _id();
    _maybeEmpty.add(id);
    _pending[id] = picture.toImage((size.width * _scale).ceil(), (size.height * _scale).ceil());
    return id;
  }

  /// What [o] paints itself, without its children: the part painted
  /// before its children, and the part painted after (on top of them).
  (String?, String?) _paintAlone(r.RenderBox o) {
    if (o.size.isEmpty) return (null, null);
    final layer = r.OffsetLayer();
    final bounds = ui.Offset.zero & o.size;
    final _AloneContext context;
    try {
      context = _AloneContext(layer, bounds, [], layer);
      o.paint(context, ui.Offset.zero);
      context.finish();
    } catch (_) {
      return (null, null);
    }
    final split = context.layersBeforeChildren;
    final front = r.OffsetLayer();
    if (split != null) {
      // Move the layers painted after the first child to their own image.
      final after = <r.Layer>[];
      var i = 0;
      for (var l = layer.firstChild; l != null; l = l.nextSibling) {
        if (i++ >= split) after.add(l);
      }
      for (final l in after) {
        // A handle keeps the layer alive while it has no parent.
        final handle = r.LayerHandle<r.Layer>(l);
        l.remove();
        front.append(l);
        handle.layer = null;
      }
    }
    String? image(r.OffsetLayer l) {
      if (l.firstChild == null) return null;
      final id = _id();
      _maybeEmpty.add(id);
      _pending[id] = l.toImage(bounds, pixelRatio: _scale);
      return id;
    }

    return (image(layer), image(front));
  }

  /// A region of the screenshot.
  String? _crop(ui.Rect rect) {
    final area = rect.intersect(ui.Offset.zero & ui.Size(_width.toDouble(), _height.toDouble()));
    if (area.isEmpty) return null;
    final recorder = ui.PictureRecorder();
    final canvas = ui.Canvas(recorder);
    canvas.drawImageRect(
      screenshot,
      ui.Rect.fromLTWH(area.left * _scale, area.top * _scale, area.width * _scale, area.height * _scale),
      ui.Rect.fromLTWH(0, 0, area.width * _scale, area.height * _scale),
      ui.Paint(),
    );
    final id = _id();
    _pending[id] = recorder.endRecording().toImage((area.width * _scale).ceil(), (area.height * _scale).ceil());
    return id;
  }

  /// Decoration images come from an ImageProvider, resolved again here.
  String? _provider(f.ImageProvider provider) {
    final id = _id();
    final completer = Completer<ui.Image?>();
    final stream = provider.resolve(f.ImageConfiguration.empty);
    late final f.ImageStreamListener listener;
    listener = f.ImageStreamListener(
      (info, _) {
        stream.removeListener(listener);
        if (!completer.isCompleted) completer.complete(info.image);
      },
      onError: (_, __) {
        stream.removeListener(listener);
        if (!completer.isCompleted) completer.complete(null);
      },
    );
    stream.addListener(listener);
    _pending[id] = completer.future.timeout(const Duration(seconds: 5), onTimeout: () => null);
    return id;
  }

  Future<void> finish() async {
    for (final MapEntry(:key, :value) in _pending.entries) {
      final image = await value;
      if (image == null) continue;
      if (_maybeEmpty.contains(key)) {
        final rgba = await image.toByteData(format: ui.ImageByteFormat.rawRgba);
        if (rgba == null) continue;
        var visible = false;
        final bytes = rgba.buffer.asUint8List();
        for (var i = 3; i < bytes.length; i += 4) {
          if (bytes[i] != 0) {
            visible = true;
            break;
          }
        }
        if (!visible) continue;
      }
      final png = await image.toByteData(format: ui.ImageByteFormat.png);
      if (png != null) images[key] = png.buffer.asUint8List();
    }
    _pending.clear();
  }

  /// Drops nodes whose image turned out empty, and groups left empty.
  List<Map<String, Object?>> prune(List<Map<String, Object?>> nodes) => [
    for (final n in nodes)
      if (n['type'] == 'image' && !images.containsKey(n['image']))
        ...const <Map<String, Object?>>[]
      else if (n['children'] case final List<Map<String, Object?>> kids)
        ...(() {
          final kept = prune(kids);
          if (kept.isEmpty && n['type'] == 'group') return const <Map<String, Object?>>[];
          return [{...n, 'children': kept}];
        })()
      else if (n['type'] == 'box' && n['image'] != null && !images.containsKey(n['image']))
        {...n, 'image': null}
      else
        n,
  ];

  /// The `Ink` widget that [o] is the topmost render object of: its
  /// decoration is painted on the Material below, not by [o].
  f.Ink? _ink(r.RenderObject o) {
    final creator = o.debugCreator;
    if (creator is! f.DebugCreator) return null;
    f.Ink? ink;
    var depth = 0;
    creator.element.visitAncestorElements((e) {
      if (e.widget is f.Ink && identical(e.renderObject, o)) ink = e.widget as f.Ink;
      return ink == null && ++depth < 6;
    });
    return ink;
  }

  String _creator(r.RenderObject o) {
    final creator = o.debugCreator;
    if (creator is f.DebugCreator) {
      return creator.element.widget.runtimeType.toString().split('<').first;
    }
    return o.runtimeType.toString();
  }

  bool _createdBy<T>(r.RenderObject o) {
    final creator = o.debugCreator;
    if (creator is! f.DebugCreator) return false;
    var found = false;
    var depth = 0;
    creator.element.visitAncestorElements((e) {
      if (e.widget is T) found = true;
      return !found && ++depth < 4;
    });
    return found || creator.element.widget is T;
  }

  ui.Rect _bounds(r.RenderBox box) =>
      r.MatrixUtils.transformRect(box.getTransformTo(null), ui.Offset.zero & box.size);

  final _paintOrder = <r.RenderObject, List<r.RenderObject>>{};

  /// The children [o] paints, in the order it paints them: offstage routes
  /// and widgets, and hidden IndexedStack children, are left out, and a
  /// text field's background comes before its text even though it is its
  /// last child. Found by replaying [o]'s paint into a recording context.
  List<r.RenderObject> _paintedChildren(r.RenderObject o) => _paintOrder.putIfAbsent(o, () {
    final painted = <r.RenderObject>[];
    final layer = r.OffsetLayer();
    try {
      final context = _AloneContext(layer, o.paintBounds, painted, layer);
      o.paint(context, ui.Offset.zero);
      context.finish();
    } catch (_) {
      painted.clear();
      if (!(o is r.RenderOffstage && o.offstage)) o.visitChildren(painted.add);
    }
    final seen = <r.RenderObject>{};
    return [for (final c in painted) if (seen.add(c)) c];
  });

  List<Map<String, Object?>> children(r.RenderObject o) => [
    for (final c in _paintedChildren(o)) ...record(c),
  ];

