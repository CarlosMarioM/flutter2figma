/// A device falls back to its system font for families the app doesn't
/// bundle (e.g. a theme naming a font that isn't installed). The test
/// environment would fall back to a box font instead, so Roboto is
/// registered under those names.
Future<bool> _loadMissingFamilies(r.RenderObject root) async {
  final families = <String>{};
  void visit(r.RenderObject o) {
    if (o is r.RenderParagraph) {
      o.text.visitChildren((span) {
        final family = span.style?.fontFamily;
        if (family != null) families.add(family);
        return true;
      });
      final family = o.text.style?.fontFamily;
      if (family != null) families.add(family);
    }
    o.visitChildren(visit);
  }

  visit(root);
  final missing = families.difference(_loadedFamilies);
  for (final family in missing) {
    await _loadFamily(family, _robotoFiles.map((b) => Future.value(ByteData.sublistView(b))));
  }
  return missing.isNotEmpty;
}

