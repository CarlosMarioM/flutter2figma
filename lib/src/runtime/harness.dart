  List<Map<String, Object?>> record(r.RenderObject o) {
    if (o is! r.RenderBox) {
      // Slivers and views: record their box descendants.
      return children(o);
    }
    if (!o.hasSize || o.size.isEmpty && o is! r.RenderParagraph) {
      return o.hasSize ? const [] : children(o);
    }
    final rect = _bounds(o);
    final name = _creator(o);
    Map<String, Object?> node(String type, [Map<String, Object?> props = const {}]) => {
      'type': type,
      'name': name,
      'rect': _rect(rect),
      ...props,
    };

    // Opacity and clips wrap their content.
    if (o is r.RenderOpacity || o is r.RenderAnimatedOpacity) {
      final opacity = o is r.RenderOpacity ? o.opacity : (o as r.RenderAnimatedOpacity).opacity.value;
      if (opacity == 0) return const [];
      if (opacity == 1) return children(o);
      return [node('group', {'opacity': opacity, 'children': children(o)})];
    }
    if (o is r.RenderClipRect || o is r.RenderClipRRect || o is r.RenderClipOval || o is r.RenderClipPath) {
      double? radius;
      if (o is r.RenderClipRRect) {
        final br = o.borderRadius.resolve(ui.TextDirection.ltr);
        radius = br.topLeft.x;
      } else if (o is r.RenderClipOval) {
        radius = o.size.shortestSide / 2;
      }
      return [node('group', {'clip': true, 'radius': radius, 'children': children(o)})];
    }

    if (o is r.RenderParagraph) return [_text(o, node)];
    if (o is r.RenderEditable) {
      return [node('text', _textProps(o.text ?? const f.TextSpan(), o.textAlign, o.maxLines))];
    }
    if (o is r.RenderImage) {
      final image = o.image;
      if (image == null) return const [];
      return [node('image', {'image': _encode(image), 'fit': o.fit?.name ?? 'scaleDown'})];
    }
    if (o is r.RenderCustomPaint) {
      final back = o.painter == null ? null : _paint(o.painter!, o.size);
      final front = o.foregroundPainter == null || o.foregroundPainter.runtimeType.toString().contains('Scrollbar')
          ? null
          : _paint(o.foregroundPainter!, o.size);
      final inner = children(o);
      if (back == null && front == null) return inner;
      return [
        node('group', {
          'children': [
            if (back != null) node('image', {'image': back, 'fit': 'fill', 'name': '${name} painter'}),
            ...inner,
            if (front != null) node('image', {'image': front, 'fit': 'fill', 'name': '${name} painter'}),
          ],
        }),
      ];
    }
    if (o is r.RenderDecoratedBox) {
      final props = _decoration(o.decoration, o.size);
      if (props == null) return children(o);
      return [node('box', {...props, 'children': children(o)})];
    }
    if (o is r.RenderPhysicalModel) {
      return [
        node('box', {
          'fill': _hex(o.color),
          'elevation': o.elevation,
          'shadowColor': _hex(o.shadowColor),
          'radius': o.shape == f.BoxShape.circle
              ? o.size.shortestSide / 2
              : o.borderRadius?.resolve(ui.TextDirection.ltr).topLeft.x,
          'clip': o.clipBehavior != ui.Clip.none,
          'children': children(o),
        }),
      ];
    }
    if (o is r.RenderPhysicalShape) {
      final clipper = o.clipper;
      final shape = clipper is f.ShapeBorderClipper ? _shape(clipper.shape, o.size) : const <String, Object?>{};
      return [
        node('box', {
          'fill': _hex(o.color),
          'elevation': o.elevation,
          'shadowColor': _hex(o.shadowColor),
          ...shape,
          'clip': o.clipBehavior != ui.Clip.none,
          'children': children(o),
        }),
      ];
    }
    if (o.runtimeType.toString() == '_RenderColoredBox') {
      final creator = o.debugCreator;
      final widget = creator is f.DebugCreator ? creator.element.widget : null;
      if (widget is f.ColoredBox) {
        return [node('box', {'fill': _hex(widget.color), 'children': children(o)})];
      }
    }

    final ink = _ink(o);
    final inkDecoration = ink?.decoration;
    if (inkDecoration != null) {
      final props = _decoration(inkDecoration, o.size);
      if (props != null) return [node('box', {...props, 'children': children(o)})];
    }

    final inner = children(o);
    final type = o.runtimeType.toString();
    final isLeaf = inner.isEmpty && _paintedChildren(o).isEmpty;
    if (!isLeaf && !_silent.contains(type) && !_noPaint.contains(type)) {
      // A container we don't model may paint too (a chip's checkmark):
      // keep what it paints itself, under its children.
      final (back, front) = _paintAlone(o);
      if (back != null || front != null) {
        return [
          node('group', {
            'children': [
              if (back != null) node('image', {'image': back, 'fit': 'fill', 'crop': type}),
              ...inner,
              if (front != null) node('image', {'image': front, 'fit': 'fill', 'crop': type}),
            ],
          }),
        ];
      }
    }
    if (isLeaf && !_silent.contains(type)) {
      // Something we don't model paints here: keep its pixels.
      final id = _crop(rect);
      if (id != null) return [node('image', {'image': id, 'fit': 'fill', 'crop': type})];
    }
    if (o is r.RenderFlex && inner.length > 1) {
      return [node('group', {'flex': o.direction.name, 'children': inner})];
    }
    return inner;
  }

  Map<String, Object?> _text(r.RenderParagraph o, Map<String, Object?> Function(String, [Map<String, Object?>]) node) {
    final style = _style(o.text);
    final family = style?.fontFamily ?? '';
    final plain = o.text.toPlainText();
    final isIcon = family == 'MaterialIcons' || family.endsWith('CupertinoIcons');
    if (isIcon && plain.runes.length == 1) {
      return node('icon', {
        'family': family.endsWith('CupertinoIcons') ? 'CupertinoIcons' : family,
        'codePoint': plain.runes.first,
        'size': style?.fontSize,
        'color': _hex(style?.color),
      });
    }
    if (_createdBy<f.Icon>(o)) {
      // An icon from a font Figma won't have: keep its pixels.
      final id = _crop(_bounds(o));
      if (id != null) return node('image', {'image': id, 'fit': 'fill'});
    }
    return node('text', _textProps(o.text, o.textAlign, o.maxLines));
  }

  f.TextStyle? _style(f.InlineSpan span) {
    var style = span.style;
    f.TextStyle? first;
    span.visitChildren((child) {
      if (identical(child, span)) return true;
      first ??= child.style;
      return first == null;
    });
    if (first != null) style = style?.merge(first) ?? first;
    return style;
  }

  Map<String, Object?> _textProps(f.InlineSpan span, ui.TextAlign align, int? maxLines) {
    final style = _style(span);
    return {
      'text': span.toPlainText(),
      'style': {
        'family': style?.fontFamily,
        'size': style?.fontSize,
        'weight': style?.fontWeight?.value,
        'italic': style?.fontStyle == ui.FontStyle.italic,
        'color': _hex(style?.color ?? style?.foreground?.color),
        'height': style?.height,
        'letterSpacing': style?.letterSpacing,
        'decoration': style?.decoration?.toString(),
      },
      'align': align.name,
      'maxLines': maxLines,
    };
  }

  Map<String, Object?>? _decoration(f.Decoration decoration, ui.Size size) {
    if (decoration is f.BoxDecoration) {
      final border = decoration.border;
      Map<String, Object?>? stroke;
      if (border is f.Border && border.isUniform && border.top.style != f.BorderStyle.none) {
        stroke = {'color': _hex(border.top.color), 'width': border.top.width};
      } else if (border is f.Border && border.bottom.style != f.BorderStyle.none && border.bottom.width > 0) {
        // A divider-like bottom border.
        stroke = {'color': _hex(border.bottom.color), 'width': border.bottom.width, 'side': 'bottom'};
      } else if (border is f.Border && border.top.style != f.BorderStyle.none && border.top.width > 0) {
        stroke = {'color': _hex(border.top.color), 'width': border.top.width, 'side': 'top'};
      }
      final gradient = decoration.gradient;
      final image = decoration.image;
      final radius = decoration.shape == f.BoxShape.circle
          ? size.shortestSide / 2
          : decoration.borderRadius?.resolve(ui.TextDirection.ltr).topLeft.x;
      return {
        'fill': _hex(decoration.color),
        if (gradient != null) 'gradient': _gradient(gradient),
        'radius': radius,
        'stroke': stroke,
        'shadows': [
          for (final b in decoration.boxShadow ?? const <f.BoxShadow>[])
            {'color': _hex(b.color), 'x': b.offset.dx, 'y': b.offset.dy, 'blur': b.blurRadius, 'spread': b.spreadRadius},
        ],
        if (image != null) 'image': _provider(image.image),
        if (image != null) 'fit': image.fit?.name ?? 'scaleDown',
      };
    }
    if (decoration is f.ShapeDecoration) {
      return {
        'fill': _hex(decoration.color),
        ..._shape(decoration.shape, size),
        'shadows': [
          for (final b in decoration.shadows ?? const <f.BoxShadow>[])
            {'color': _hex(b.color), 'x': b.offset.dx, 'y': b.offset.dy, 'blur': b.blurRadius, 'spread': b.spreadRadius},
        ],
      };
    }
    return null;
  }

  Map<String, Object?> _gradient(f.Gradient g) {
    List<double> point(f.AlignmentGeometry a) {
      final r = a.resolve(ui.TextDirection.ltr);
      return [(r.x + 1) / 2, (r.y + 1) / 2];
    }

    return {
      'type': g is f.RadialGradient ? 'radial' : 'linear',
      'colors': [for (final c in g.colors) _hex(c)],
      'stops': g.stops,
      if (g is f.LinearGradient) 'begin': point(g.begin),
      if (g is f.LinearGradient) 'end': point(g.end),
      if (g is f.RadialGradient) 'center': point(g.center),
      if (g is f.RadialGradient) 'radius': g.radius,
    };
  }

  Map<String, Object?> _shape(f.ShapeBorder shape, ui.Size size) {
    double? radius;
    f.BorderSide? side;
    if (shape is f.RoundedRectangleBorder) {
      radius = shape.borderRadius.resolve(ui.TextDirection.ltr).topLeft.x;
      side = shape.side;
    } else if (shape is f.StadiumBorder) {
      radius = size.shortestSide / 2;
      side = shape.side;
    } else if (shape is f.CircleBorder) {
      radius = size.shortestSide / 2;
      side = shape.side;
    } else if (shape is f.ContinuousRectangleBorder) {
      radius = shape.borderRadius.resolve(ui.TextDirection.ltr).topLeft.x / 2;
      side = shape.side;
    } else if (shape is f.OutlinedBorder) {
      side = shape.side;
    }
    return {
      'radius': radius,
      if (side != null && side.style != f.BorderStyle.none && side.width > 0)
        'stroke': {'color': _hex(side.color), 'width': side.width},
    };
  }
}

